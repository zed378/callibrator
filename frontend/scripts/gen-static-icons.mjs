#!/usr/bin/env node
/**
 * P10-13 (ADR-098 Amendment 2): writes src/components/icons/static.tsx — the
 * lucide icons the public pages and the root error / not-found boundaries use,
 * as plain server-renderable SVG components.
 *
 * Why: lucide-react 1.x marks its `Icon` base `"use client"` (it reads a
 * context), so every lucide icon — even one drawn by a server component — is a
 * client reference: ~11 KB of runtime plus each icon's module in the page's
 * first-load JavaScript. The root not-found boundary alone put that runtime on
 * every page. These components draw the same paths (lucide, ISC licence) with
 * no runtime at all.
 *
 *   node scripts/gen-static-icons.mjs     # after adding a name to ICONS
 */
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const lucideEsm = path.join(path.dirname(require.resolve("lucide-react/package.json")), "dist", "esm");
const version = JSON.parse(fs.readFileSync(path.join(lucideEsm, "..", "..", "package.json"), "utf8")).version;

/** Export names, exactly as lucide-react exports them, so a swap is one import line. */
const ICONS = [
  "AlertTriangle",
  "ArrowLeft",
  "ArrowRight",
  "Check",
  "CircleAlert",
  "CircleCheck",
  "CircleHelp",
  "CircleX",
  "Download",
  "ExternalLink",
  "Eye",
  "EyeOff",
  "FileText",
  "Gauge",
  "Home",
  "KeyRound",
  "LayoutDashboard",
  "Link2",
  "Mail",
  "Menu",
  "MessageCircle",
  "Plus",
  "QrCode",
  "RefreshCw",
  "Share2",
  "X",
];

const barrel = fs.readFileSync(path.join(lucideEsm, "lucide-react.mjs"), "utf8");
const fileFor = (name) => {
  const re = new RegExp(`export \\{[^}]*\\bdefault as ${name}\\b[^}]*\\} from '\\./icons/([a-z0-9-]+)\\.mjs'`);
  const m = barrel.match(re);
  if (!m) throw new Error(`lucide-react exports no icon named ${name}`);
  return m[1];
};

/** The icon's node list, read from its module's `__iconData` literal. */
const nodeFor = (file) => {
  const src = fs.readFileSync(path.join(lucideEsm, "icons", `${file}.mjs`), "utf8");
  const m = src.match(/const __iconData = (\{[\s\S]*?\n\});/);
  if (!m) throw new Error(`cannot read the icon data of ${file}`);
  // The literal is plain data (tag names, attribute objects of strings/numbers).
  const data = /** @type {{ node: Array<[string, Record<string, string | number>]> }} */ (
    new Function(`return ${m[1]}`)()
  );
  return data.node;
};

const jsxAttr = (k, v) => `${k.replace(/-([a-z])/g, (_, c) => c.toUpperCase())}=${JSON.stringify(String(v))}`;

const body = ICONS.map((name) => {
  const file = fileFor(name);
  const children = nodeFor(file)
    .map(([tag, attrs]) => {
      const a = Object.entries(attrs)
        .filter(([k]) => k !== "key")
        .map(([k, v]) => jsxAttr(k, v))
        .join(" ");
      return `    <${tag} ${a} />`;
    })
    .join("\n");
  return `/** lucide \`${file}\` */\nexport const ${name}: StaticIcon = (props) => (\n  <Svg {...props}>\n${children}\n  </Svg>\n);`;
}).join("\n\n");

const out = `// GENERATED by scripts/gen-static-icons.mjs from lucide-react ${version} — do not edit by hand.
//
// P10-13 (ADR-098 Amendment 2): lucide's icons as plain SVG components with no
// client runtime (lucide-react's own \`Icon\` is "use client"). Same paths, same
// 24-unit grid, stroke 2, round caps. Decorative by default (aria-hidden); give
// an icon that carries meaning an \`aria-label\` and set \`aria-hidden={false}\`.
//
// Icon paths: lucide (https://lucide.dev), ISC licence, © Lucide Contributors.
import React from "react";

export type StaticIconProps = React.SVGProps<SVGSVGElement>;
export type StaticIcon = (props: StaticIconProps) => React.JSX.Element;

function Svg({ children, ...props }: StaticIconProps) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={24}
      height={24}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      {...props}
    >
      {children}
    </svg>
  );
}

${body}
`;

const target = path.resolve(here, "..", "src", "components", "icons", "static.tsx");
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, out);
console.log(`wrote ${path.relative(process.cwd(), target)} (${ICONS.length} icons, lucide-react ${version})`);
